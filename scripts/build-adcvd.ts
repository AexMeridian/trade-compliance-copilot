// Turns a saved official AD/CVD export into the migration that fills adcvd_orders.
//
//   npx tsx scripts/build-adcvd.ts orders.csv --as-of 2026-11-22 --source "USITC AD/CVD orders in effect"
//   npx tsx scripts/build-adcvd.ts orders.csv --as-of 2026-11-22 --source "ITA ACCESS AD/CVD Search" --first 111
//
// The CSV needs these columns (headers exactly): case_number, country_code (ISO 2-letter), country, product, order_date (YYYY-MM-DD),
// rate_min, rate_max, hts_prefixes (digits, separated by ; or ,), chapters, source_url. Only case_number, country_code and product are required.
// Save the file from the official page yourself: none of the official sources allows automated download (see src/lib/adcvd.ts).
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { adcvdMigrationSql, parseAdcvdCsv } from '../src/lib/adcvd.js';

const args = process.argv.slice(2);
const file = args[0];
const val = (flag: string) => (args.includes(flag) ? args[args.indexOf(flag) + 1] : undefined);
const asOf = val('--as-of');
const source = val('--source');
if (!file || file.startsWith('--') || !existsSync(file) || !asOf || !/^\d{4}-\d{2}-\d{2}$/.test(asOf) || !source) {
  console.error('Usage: npx tsx scripts/build-adcvd.ts <orders.csv> --as-of YYYY-MM-DD --source "<where the export came from>" [--first <migration number>]');
  process.exit(2);
}
const orders = parseAdcvdCsv(readFileSync(file, 'utf8'), { source, asOf, defaultUrl: 'https://access.trade.gov/adcvd' });
if (orders.length === 0) {
  console.error('No usable rows (case numbers must look like A-570-001 or C-570-002).');
  process.exit(1);
}
// Migrations 0110-0119 are reserved for this feature (0110 creates the table).
const used = readdirSync('migrations').map((f) => Number(f.slice(0, 4))).filter((n) => n >= 110 && n <= 119);
const first = val('--first') ? Number(val('--first')) : Math.max(110, ...used) + 1;
if (first < 111 || first > 119) {
  console.error('Migration numbers 0110-0119 are used up; renumber by hand.');
  process.exit(1);
}
const name = `migrations/${String(first).padStart(4, '0')}_adcvd_orders_${asOf.replace(/-/g, '')}.sql`;
writeFileSync(name, `-- AD/CVD orders in force as of ${asOf} (${source}); ${orders.length} orders. Generated by scripts/build-adcvd.ts; replaces the table's contents.\n${adcvdMigrationSql(orders)}`);
console.log(`Wrote ${name} (${orders.length} orders).`);
