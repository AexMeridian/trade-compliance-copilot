// Rebuilds Country Groups (15 CFR Part 740, Supplement No. 1) from the official eCFR text instead of by hand.
//
//   npx tsx scripts/build-country-groups.ts            report whether the published groups differ from data/country-groups.json (exit 1 if they do)
//   npx tsx scripts/build-country-groups.ts --write    also write the new snapshot and the next numbered migration
//   npx tsx scripts/build-country-groups.ts --write --first 71   number the migration 0071 (the initial load) instead of the next free number
//   npx tsx scripts/build-country-groups.ts --xml part740.xml --as-of 2026-11-19   read a saved copy of the eCFR XML instead of downloading it
//
// Run weekly by .github/workflows/ccl-pr.yml. A country name it does not recognise stops it instead of guessing.

import { existsSync, readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { parseCountryGroups, groupCountryIso } from '../src/lib/countryGroupsParse.js';

const SNAPSHOT = 'data/country-groups.json';
const PAGE = 'https://www.ecfr.gov/current/title-15/subtitle-B/chapter-VII/subchapter-C/part-740/appendix-Supplement%20No.%201%20to%20Part%20740';

interface Snapshot {
  asOf: string;
  /** ISO country code -> the name the eCFR prints and its groups. */
  countries: Record<string, { name: string; groups: string[] }>;
}

const args = process.argv.slice(2);
const write = args.includes('--write');
const argVal = (flag: string) => (args.includes(flag) ? args[args.indexOf(flag) + 1] : undefined);
const sq = (s: string) => `'${s.replace(/'/g, "''")}'`;

async function get(url: string): Promise<Response> {
  const res = await fetch(url, { headers: { 'user-agent': 'AexTerminal-data-sync/1.0 (+https://aexterminal.com)' } });
  if (!res.ok) throw new Error(`${url} -> HTTP ${res.status}`);
  return res;
}

let xml: string;
let asOf: string;
const xmlFile = argVal('--xml');
if (xmlFile) {
  xml = readFileSync(xmlFile, 'utf8');
  asOf = argVal('--as-of') ?? new Date().toISOString().slice(0, 10);
} else {
  const titles = (await (await get('https://www.ecfr.gov/api/versioner/v1/titles.json')).json()) as { titles: { number: number; up_to_date_as_of: string }[] };
  const date = titles.titles.find((t) => t.number === 15)?.up_to_date_as_of;
  if (!date) throw new Error('The eCFR did not report an up-to-date date for title 15');
  asOf = date;
  xml = await (await get(`https://www.ecfr.gov/api/versioner/v1/full/${asOf}/title-15.xml?part=740&appendix=Supplement%20No.%201%20to%20Part%20740`)).text();
}

const members = parseCountryGroups(xml);
const unmapped = [...new Set(members.filter((m) => !groupCountryIso(m.name)).map((m) => m.name))];
if (unmapped.length > 0) {
  console.error(`Not mapped to a country code, add them to ALIAS in src/lib/countryGroupsParse.ts: ${unmapped.join(' | ')}`);
  process.exit(2);
}
const countries: Snapshot['countries'] = {};
for (const m of members) {
  const iso = groupCountryIso(m.name)!;
  (countries[iso] ??= { name: m.name, groups: [] }).groups.push(m.group);
}
for (const c of Object.values(countries)) c.groups.sort();
const snapshot: Snapshot = { asOf, countries: Object.fromEntries(Object.entries(countries).sort(([a], [b]) => a.localeCompare(b))) };

const previous: Snapshot | null = existsSync(SNAPSHOT) ? (JSON.parse(readFileSync(SNAPSHOT, 'utf8')) as Snapshot) : null;
const same = !!previous && JSON.stringify(previous.countries) === JSON.stringify(snapshot.countries);
console.log(`${Object.keys(snapshot.countries).length} countries in ${new Set(members.map((m) => m.group)).size} groups, ${members.length} memberships (eCFR as of ${asOf}); ${same ? 'identical to the stored snapshot' : previous ? 'DIFFERENT from the stored snapshot' : 'no stored snapshot yet'}`);
if (previous && !same) {
  for (const [iso, c] of Object.entries(snapshot.countries)) {
    const old = previous.countries[iso];
    if (!old) console.log(`  new: ${iso} ${c.name}: ${c.groups.join(' ')}`);
    else if (old.groups.join() !== c.groups.join()) console.log(`  changed: ${iso} ${c.name}: ${old.groups.join(' ')} -> ${c.groups.join(' ')}`);
  }
  for (const iso of Object.keys(previous.countries)) if (!snapshot.countries[iso]) console.log(`  removed: ${iso}`);
}
if (same) process.exit(0);
if (!write) process.exit(1);

mkdirSync('data', { recursive: true });
writeFileSync(SNAPSHOT, JSON.stringify(snapshot, null, 1) + '\n');
const next = argVal('--first') ? Number(argVal('--first')) : Math.max(...readdirSync('migrations').map((f) => Number(f.slice(0, 4)))) + 1;
const file = `migrations/${String(next).padStart(4, '0')}_country_groups_${asOf.replace(/-/g, '')}.sql`;
const values = Object.entries(snapshot.countries).flatMap(([iso, c]) => c.groups.map((g) => `(${sq(iso)}, ${sq(g)}, ${sq(c.name)}, ${sq(PAGE)}, ${sq(asOf)})`));
const sql = `-- Country Groups (15 CFR 740 Supp. No. 1), eCFR text as of ${asOf}. Generated by scripts/build-country-groups.ts.
DELETE FROM country_groups;
INSERT INTO country_groups (country_code, group_code, country_name, source_url, as_of) VALUES
${values.join(',\n')};
`;
writeFileSync(file, sql);
console.log(`wrote ${SNAPSHOT} and ${file} (${sql.length} bytes)`);
