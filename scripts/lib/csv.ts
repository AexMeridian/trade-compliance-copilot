// Minimal RFC-4180-ish CSV line splitter (double-quote enclosed fields, "" as an
// escaped literal quote, comma delimiter). Good enough for the Census AES
// concordance file's simple, consistently-quoted format -- avoids pulling in a
// full CSV dependency for one file.

export function parseCsvLine(line: string): string[] {
  const fields: string[] = [];
  let cur = '';
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (inQuotes) {
      if (c === '"') {
        if (line[i + 1] === '"') {
          cur += '"';
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        cur += c;
      }
    } else if (c === '"') {
      inQuotes = true;
    } else if (c === ',') {
      fields.push(cur);
      cur = '';
    } else {
      cur += c;
    }
  }
  fields.push(cur);
  return fields;
}
