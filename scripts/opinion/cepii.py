"""Turns CEPII's GeoDist dyadic file into src/lib/power/cepii.generated.ts.

Offline only: the Worker never runs this. CEPII GeoDist (Mayer and Zignago 2011) is licensed Etalab 2.0 (open, commercial reuse with
attribution). Download https://www.cepii.fr/distance/dist_cepii.zip, unzip it, and run (needs `pip install xlrd`):

    python scripts/opinion/cepii.py path/to/dist_cepii.xls

For each country and each of seven partner powers it records two facts from the file: whether the two share an official language
(`comlang_off`) and whether they have ever had a colonial relationship (`colony`). Nothing else leaves this script.
"""
import json, os, sys, urllib.request
import xlrd

PARTNERS = ['US', 'GB', 'FR', 'ES', 'PT', 'RU', 'CN']
# Codes the 2004-era file still uses, mapped to today's two-letter codes. Territories and defunct states with no clean successor are dropped.
LEGACY = {'ZAR': 'CD', 'ROM': 'RO', 'TMP': 'TL', 'YUG': 'RS', 'SCG': 'RS', 'PAL': 'PS', 'WBG': 'PS'}


def iso3_map():
    d = json.load(urllib.request.urlopen('https://api.worldbank.org/v2/country?format=json&per_page=400', timeout=60))
    m = {r['id']: r['iso2Code'] for r in d[1] if r['region']['id'] != 'NA' and len(r['iso2Code']) == 2}
    m.update(LEGACY)
    return m


def main(path):
    iso = iso3_map()
    sh = xlrd.open_workbook(path).sheet_by_index(0)
    head = [sh.cell_value(0, c) for c in range(sh.ncols)]
    col = {h: i for i, h in enumerate(head)}
    ties = {}
    unmapped = set()
    for r in range(1, sh.nrows):
        o, d = sh.cell_value(r, col['iso_o']), sh.cell_value(r, col['iso_d'])
        a, b = iso.get(o), iso.get(d)
        if not a:
            unmapped.add(o)
            continue
        if not b or b not in PARTNERS or a == b:
            continue
        t = ties.setdefault(a, {'lang': [], 'colony': []})
        if sh.cell_value(r, col['comlang_off']) == 1 and b not in t['lang']:
            t['lang'].append(b)
        if sh.cell_value(r, col['colony']) == 1 and b not in t['colony']:
            t['colony'].append(b)
    out = {cc: {'lang': sorted(v['lang']), 'colony': sorted(v['colony'])} for cc, v in sorted(ties.items())}
    dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'src', 'lib', 'power', 'cepii.generated.ts')
    with open(dst, 'w', encoding='utf8') as fh:
        fh.write('// GENERATED by scripts/opinion/cepii.py from CEPII GeoDist (Mayer and Zignago 2011, Etalab 2.0). Do not edit by hand.\n')
        fh.write('// For each country: partner powers it shares an official language with, and partners it has ever had a colonial relationship with.\n')
        fh.write('export const CEPII_PARTNERS = %s as const;\n' % json.dumps(PARTNERS))
        fh.write('export interface CepiiTies { lang: string[]; colony: string[] }\n')
        fh.write('export const CEPII_TIES: Record<string, CepiiTies> = %s;\n' % json.dumps(out, indent=1))
    print(len(out), 'countries;', sum(1 for v in out.values() if v['lang']), 'with a shared official language;', 'unmapped codes skipped:', sorted(unmapped))


main(sys.argv[1])
